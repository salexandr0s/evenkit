import { foundation, metadata } from "./foundation.js";
import { colorModes, validateBrand, type Brand, type ColorMode } from "./schema.js";
import { themeNames, themes, type ThemeName } from "./themes.js";

export type CssVariables = Record<`--pk-${string}`, string>;

function kebab(value: string): string {
  return value.replaceAll("_", "-").replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function flatten(value: unknown, path: string[] = []): CssVariables {
  const variables: CssVariables = {};
  if (typeof value === "string" || typeof value === "number") {
    variables[`--pk-${path.map(kebab).join("-")}`] = String(value);
  } else if (value !== null && typeof value === "object") {
    for (const [key, child] of Object.entries(value)) {
      Object.assign(variables, flatten(child, [...path, key]));
    }
  }
  return variables;
}

export const staticCssVariables: Readonly<CssVariables> = Object.freeze(flatten(foundation));

function brandVariables(brand: Brand, mode: ColorMode): CssVariables {
  const colors: CssVariables = {};
  for (const [role, value] of Object.entries(brand.modes[mode])) {
    const name: `--pk-${string}` = role.startsWith("chart-series-") ? `--pk-${role}` : `--pk-color-${role}`;
    colors[name] = value;
  }
  return {
    ...colors,
    "--pk-font-family-sans": brand.fontFamily,
    "--pk-font-family-heading": brand.headingFamily,
    "--pk-radius-sm": brand.radius.sm,
    "--pk-radius-md": brand.radius.md,
    "--pk-radius-lg": brand.radius.lg,
  };
}

/** Resolved document variables, suitable for inspection or style APIs. */
export function cssVariables(themeName: ThemeName, mode: ColorMode): CssVariables {
  return { ...staticCssVariables, ...brandVariables(themes[themeName], mode) };
}

function declarations(variables: CssVariables): string {
  return Object.entries(variables).map(([name, value]) => `  ${name}: ${value};`).join("\n");
}

function themeSelector(id: string, mode?: ColorMode): string {
  const suffix = mode ? `[data-kit-mode="${mode}"]` : "";
  const selected = `:root[data-kit-theme="${id}"]${suffix}`;
  return id === "neutral" ? `:root:not([data-kit-theme])${suffix},\n${selected}` : selected;
}

function systemSelector(id: string): string {
  const selected = `:root[data-kit-theme="${id}"]:not([data-kit-mode])`;
  return id === "neutral" ? `:root:not([data-kit-theme]):not([data-kit-mode]),\n${selected}` : selected;
}

function brandCss(brand: Brand): string {
  const light = `${themeSelector(brand.id)} {\n${declarations(brandVariables(brand, "light"))}\n  color-scheme: light;\n}`;
  const dark = `${themeSelector(brand.id, "dark")} {\n${declarations(brandVariables(brand, "dark"))}\n  color-scheme: dark;\n}`;
  const system = `@media (prefers-color-scheme: dark) {\n${systemSelector(brand.id)} {\n${declarations(brandVariables(brand, "dark"))}\n  color-scheme: dark;\n}\n}`;
  return `${light}\n\n${dark}\n\n${system}`;
}

/** Validate a custom brand and emit CSS scoped to its safe document-theme ID. */
export function createBrandCss(input: unknown): string {
  return `${brandCss(validateBrand(input))}\n`;
}

export function generateCss(): string {
  return [
    `/* Generated by @evenkit/tokens ${metadata.version}. Edit TypeScript sources, not this file. */`,
    `:root {\n${declarations({ ...staticCssVariables })}\n}`,
    ...themeNames.map((name) => createBrandCss(themes[name]).trimEnd()),
    "",
  ].join("\n\n");
}

export const tokenDocument = {
  metadata,
  foundation,
  themes,
  modes: colorModes,
  selectors: {
    theme: "data-kit-theme",
    mode: "data-kit-mode",
    system: "Omit data-kit-mode to follow prefers-color-scheme.",
    scope: "Document root only.",
  },
} as const;
