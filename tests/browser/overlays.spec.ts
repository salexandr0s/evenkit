import { expect, test } from "@playwright/test";

test("action menus preserve check/radio choices, skip disabled items, and reach submenus by keyboard", async ({ page }) => {
  await page.goto("/#dropdown-menu");
  const trigger = page.getByRole("button", { name: "Project actions", exact: true });
  await trigger.focus();
  await trigger.press("ArrowDown");
  await expect(page.getByRole("menuitem", { name: "Open details", exact: true })).toBeFocused();
  await page.keyboard.press("ArrowDown");
  const archived = page.getByRole("menuitemcheckbox", { name: "Show archived projects" });
  await expect(archived).toBeFocused();
  await archived.press("Space");
  await expect(archived).toBeChecked();
  await expect(archived).toBeVisible();
  await page.getByRole("menuitemradio", { name: "Compact", exact: true }).click();
  await expect(page.getByRole("menuitemradio", { name: "Compact", exact: true })).toBeChecked();
  const submenu = page.getByRole("menuitem", { name: "Export", exact: true });
  await submenu.focus();
  await submenu.press("ArrowRight");
  const csv = page.getByRole("menuitem", { name: "CSV file", exact: true });
  await expect(csv).toBeFocused();
  await csv.press("Enter");
  await expect(page.getByRole("menu")).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "CSV export selected" })).toBeVisible();

  await page.setViewportSize({ width: 360, height: 780 });
  await page.getByRole("button", { name: "RTL actions", exact: true }).click();
  const menu = page.getByRole("menu");
  await expect(menu).toHaveCSS("direction", "rtl");
  expect(await menu.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  expect((await page.getByRole("menuitem").boundingBox())?.height).toBeGreaterThanOrEqual(44);
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "RTL actions", exact: true })).toBeFocused();
});

test("popovers and menus remain usable above a modal and restore focus within it", async ({ page }) => {
  const runtimeErrors: string[] = [];
  page.on("pageerror", error => runtimeErrors.push(error.message));
  await page.goto("/#popover");
  const launcher = page.getByRole("button", { name: "Open nested overlays" });
  await launcher.click();
  const dialog = page.getByRole("dialog", { name: "Edit project access", exact: true });
  const sharing = dialog.getByRole("button", { name: "Sharing options in dialog" });
  await sharing.click();
  const group = page.getByRole("textbox", { name: "Review group", exact: true });
  await expect(group).toBeFocused();
  await group.fill("Launch reviewers");
  const popup = page.getByRole("dialog", { name: "Sharing options", exact: true });
  const modalZ = await dialog.evaluate(element => Number(getComputedStyle(element).zIndex));
  expect(await popup.evaluate(element => Number(getComputedStyle(element).zIndex))).toBeGreaterThan(modalZ);
  await popup.getByRole("button", { name: "Done", exact: true }).click();
  await expect(sharing).toBeFocused();
  await expect(dialog).toBeVisible();
  const actions = dialog.getByRole("button", { name: "Actions in dialog" });
  await actions.click();
  await page.getByRole("menuitem", { name: "Prepare review link" }).click();
  await expect(actions).toBeFocused();
  await expect(dialog.getByRole("status")).toHaveText("The review link is ready.");
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(launcher).toBeFocused();
  expect(runtimeErrors).toEqual([]);
});

test("critical confirmation starts at cancel, retains failed requests, and invalidates a cancelled result", async ({ page }) => {
  await page.goto("/#alert-dialog");
  const trigger = page.getByRole("button", { name: "Delete project", exact: true });
  await trigger.click();
  const confirm = page.getByRole("alertdialog", { name: "Delete the sample project?" });
  const cancel = confirm.getByRole("button", { name: "Cancel deletion" });
  await expect(cancel).toBeFocused();
  await page.mouse.click(4, 4);
  await expect(confirm).toBeVisible();
  await confirm.getByRole("button", { name: "Confirm deletion" }).click();
  await expect(cancel).toBeFocused();
  await expect(confirm.getByRole("alert")).toContainText("The preview request failed");
  await expect(confirm).toBeVisible();
  await confirm.getByRole("button", { name: "Retry deletion" }).click();
  await cancel.click();
  await expect(confirm).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await trigger.click();
  await expect(confirm.getByRole("alert")).toHaveCount(0);
  await confirm.getByRole("button", { name: "Confirm deletion" }).click();
  const restore = page.getByRole("button", { name: "Restore sample project" });
  await expect(restore).toBeVisible();
  await expect(restore).toBeFocused();
  await expect(trigger).toBeDisabled();
  await restore.click();
  await expect(trigger).toBeEnabled();
});

