test("toasts pause expiry, cap current notices, restore action focus, and clear on context changes", async ({ page }) => {
  await page.clock.install();
  await page.goto("/#toast");
  await page.getByRole("button", { name: "Show saved notice" }).click();
  const notice = page.locator(".pk-toast");
  await expect(notice).toHaveCount(1);
  await notice.hover();
  await page.clock.runFor(4000);
  await expect(notice).toBeVisible();
  await page.mouse.move(0, 0);
  await page.clock.runFor(3100);
  await expect(notice).toHaveCount(0);

  const action = page.getByRole("button", { name: "Show action notice" });
  await action.click();
  const undo = page.getByRole("button", { name: "Undo archive" });
  await expect(undo).toHaveAttribute("data-shape", "icon");
  await expect(undo).toHaveText("");
  for (const [width, target] of [[1280, 24], [360, 44]] as const) {
    await page.setViewportSize({ width, height: 900 });
    const titleBox = await notice.locator(".pk-toast-title").boundingBox();
    const undoBox = await undo.boundingBox();
    const closeBox = await notice.getByRole("button", { name: "Dismiss notification" }).boundingBox();
    if (!titleBox || !undoBox || !closeBox) throw new Error("Missing inline toast controls");
    expect(undoBox.width).toBe(target);
    expect(undoBox.height).toBe(target);
    expect(undoBox.y + undoBox.height / 2).toBeCloseTo(titleBox.y + titleBox.height / 2, 1);
    expect(undoBox.x + undoBox.width).toBeLessThanOrEqual(closeBox.x);
    expect(await notice.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  }
  await page.setViewportSize({ width: 1280, height: 900 });
  await undo.focus();
  await expect(page.getByRole("tooltip", { name: "Undo archive" })).toBeVisible();
  await undo.press("Escape");
  await page.clock.runFor(200);
  await expect(page.getByRole("tooltip")).toHaveCount(0);
  await expect(notice).toBeVisible();
  await expect(undo).toBeFocused();
  await undo.press("Enter");
  await expect(notice).toHaveCount(0);
  await expect(action).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "The sample project is active." })).toBeVisible();
  await action.click();
  const dismiss = page.getByRole("button", { name: "Dismiss notification" });
  await dismiss.focus();
  await dismiss.press("Enter");
  await expect(notice).toHaveCount(0);
  await expect(action).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "The sample project is archived." })).toBeVisible();
  await page.getByRole("button", { name: "Show four notices" }).click();
  await expect(notice).toHaveCount(3);
  await expect(notice.filter({ hasText: "Current notice 1" })).toHaveCount(0);
  const draft = page.getByRole("textbox", { name: "Draft preserved across context changes" });
  const node = await draft.elementHandle();
  await draft.fill("Keep this draft");
  await page.getByRole("button", { name: "Change notification context" }).click();
  await expect(notice).toHaveCount(0);
  await expect(draft).toHaveValue("Keep this draft");
  expect(await draft.evaluate((element, original) => element === original, node)).toBe(true);
  await node?.dispose();
  // Returning to an old context name must not revive callbacks from its previous visit.
  await page.getByRole("button", { name: "Schedule delayed notice" }).click();
  await page.getByRole("button", { name: "Change notification context" }).click();
  await page.getByRole("button", { name: "Change notification context" }).click();
  await page.clock.runFor(500);
  await expect(notice).toHaveCount(0);
});

test("account menus preserve controlled preferences and show host-owned sign-out failure and retry", async ({ page }) => {
  await page.goto("/#account-menu");
  const trigger = page.getByRole("button", { name: "Open account menu for Alex Morgan" });
  await trigger.click();
  await page.getByRole("menuitemradio", { name: "Dark", exact: true }).click();
  await expect(page.getByRole("menuitemradio", { name: "Dark", exact: true })).toBeChecked();
  await expect(page.getByRole("menuitem", { name: "Billing (unavailable)" })).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(trigger).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "Appearance preference: dark" })).toBeVisible();
  await trigger.click();
  await page.getByRole("menuitem", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("menu")).toBeFocused();
  await expect(page.getByRole("alert")).toContainText("The local sign-out attempt failed");
  await page.getByRole("menuitem", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("menu")).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "The demo session has ended." })).toBeVisible();
});
