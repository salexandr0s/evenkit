test("required choices redirect native validation to the first visible invalid control", async ({ page }) => {
  await page.goto("/#checkbox");
  const region = page.getByRole("region", { name: "Required choices example" });
  const confirm = region.getByRole("checkbox", { name: "Confirm project access", exact: true });
  const access = region.getByRole("radiogroup", { name: "Access level", exact: true });
  const permission = region.getByRole("radiogroup", { name: "Editing permission", exact: true });
  const submit = region.getByRole("button", { name: "Validate required choices", exact: true });
  await submit.click();
  await expect(confirm).toBeFocused();
  await expect(confirm).toHaveAttribute("aria-invalid", "true");
  await expect(confirm).toHaveAccessibleDescription(/.+/);
  await confirm.check();
  await submit.click();
  const team = access.getByRole("radio", { name: "Team only", exact: true });
  await expect(team).toBeFocused();
  await expect(access).toHaveAttribute("aria-invalid", "true");
  await team.check();
  await submit.click();
  const view = permission.getByRole("radio", { name: "View", exact: true });
  await expect(view).toBeFocused();
  await expect(permission).toHaveAttribute("aria-invalid", "true");
  const colors = await permission.evaluate(element => {
    const probe = document.createElement("span");
    probe.style.color = "var(--pk-color-danger)";
    element.append(probe);
    const result = { actual: getComputedStyle(element).borderColor, expected: getComputedStyle(probe).color };
    probe.remove();
    return result;
  });
  expect(colors.actual).toBe(colors.expected);
  await view.check();
  await submit.click();
  const notifications = region.getByRole("switch", { name: "Require change notifications", exact: true });
  await expect(notifications).toBeFocused();
  await notifications.check();
  await submit.click();
  await expect(region.getByText("Required choices accepted.", { exact: true })).toBeVisible();
  await expect(region.getByRole("alert")).toHaveCount(0);
  await region.getByRole("button", { name: "Reset required choices", exact: true }).click();
  await expect(confirm).not.toBeChecked();
  await expect(region.getByRole("alert")).toHaveCount(0);
  await submit.click();
  await expect(confirm).toBeFocused();
});

test("controlled corrections and constraint changes clear native feedback while preserving host errors", async ({ page }) => {
  await page.goto("/#checkbox");
  const region = page.getByRole("region", { name: "Required choices example" });
  const confirm = region.getByRole("checkbox", { name: "Confirm project access", exact: true });
  const access = region.getByRole("radiogroup", { name: "Access level", exact: true });
  const permission = region.getByRole("radiogroup", { name: "Editing permission", exact: true });
  const notifications = region.getByRole("switch", { name: "Require change notifications", exact: true });
  const submit = region.getByRole("button", { name: "Validate required choices", exact: true });
  const correct = region.getByRole("button", { name: "Correct required choices", exact: true });
  const reset = region.getByRole("button", { name: "Reset required choices", exact: true });
  await submit.click();
  await expect(region.getByRole("alert")).toHaveCount(4);
  await expect(confirm).toHaveAttribute("aria-invalid", "true");
  await expect(access).toHaveAttribute("aria-invalid", "true");
  await expect(permission).toHaveAttribute("aria-invalid", "true");
  await expect(notifications).toHaveAttribute("aria-invalid", "true");
  await correct.click();
  await expect(region.getByRole("alert")).toHaveCount(0);
  for (const control of [confirm, access, permission, notifications]) await expect(control).not.toHaveAttribute("aria-invalid", "true");
  await expect(correct).toBeFocused();

  await reset.click();
  await submit.click();
  await expect(region.getByRole("alert")).toHaveCount(4);
  await region.getByRole("button", { name: "Make choices optional", exact: true }).click();
  await expect(region.getByRole("alert")).toHaveCount(0);
  await region.getByRole("button", { name: "Require choices", exact: true }).click();
  await submit.click();
  await expect(region.getByRole("alert")).toHaveCount(4);
  await region.getByRole("button", { name: "Disable required choices", exact: true }).click();
  await expect(region.getByRole("alert")).toHaveCount(0);
  await region.getByRole("button", { name: "Enable required choices", exact: true }).click();
  await submit.click();
  await expect(region.getByRole("alert")).toHaveCount(4);
  await region.getByRole("button", { name: "Show host error", exact: true }).click();
  await correct.click();
  await expect(region.getByRole("alert")).toHaveCount(1);
  await expect(region.getByRole("alert")).toHaveText("Access could not be verified by the host.");
  await expect(confirm).toHaveAttribute("aria-invalid", "true");
  await region.getByRole("button", { name: "Clear host error", exact: true }).click();
  await expect(region.getByRole("alert")).toHaveCount(0);
});

test("pending switches preserve focus, reject repeated activation, recover errors and reset native forms", async ({ page }) => {
  await page.clock.install({ time: new Date("2026-10-25T08:00:00Z") });
  await page.goto("/#switch");
  const region = page.getByRole("region", { name: "Switch recovery example" });
  const preference = region.getByRole("switch", { name: "Project notifications", exact: true });
  await expect(preference).toBeVisible();
  await page.clock.pauseAt(new Date("2026-10-25T09:00:00Z"));
  await preference.press("Space");
  await expect(preference).toHaveAttribute("aria-busy", "true");
  await expect(preference).toBeFocused();
  await preference.press("Space");
  await expect(preference).not.toBeChecked();
  await page.clock.runFor(700);
  await expect(region.getByRole("alert")).toContainText("sample save failed");
  await expect(preference).toBeFocused();
  await preference.press("Space");
  await page.clock.runFor(700);
  await expect(preference).toBeChecked();
  await expect(region.getByRole("alert")).toHaveCount(0);
  await expect(preference).toBeFocused();
  const form = region.getByRole("form", { name: "Switch form values" });
  const digest = form.getByRole("switch", { name: "Weekly digest", exact: true });
  await digest.uncheck();
  await form.getByRole("button", { name: "Inspect digest" }).click();
  await expect(form.getByRole("status")).toHaveText("Weekly digest disabled.");
  await form.getByRole("button", { name: "Reset digest" }).click();
  await page.clock.runFor(1);
  await expect(digest).toBeChecked();
  await page.setViewportSize({ width: 360, height: 900 });
  expect((await preference.boundingBox())?.height).toBeGreaterThanOrEqual(44);

  // Check the built CSS: :dir() lowering must not confuse direction with language.
  await region.evaluate(element => element.setAttribute("dir", "rtl"));
  const thumbIsOnRight = () => preference.evaluate(element => {
    const thumb = element.querySelector(".pk-switch-thumb")?.getBoundingClientRect();
    const track = element.querySelector(".pk-switch-track")?.getBoundingClientRect();
    if (!thumb || !track) throw new Error("Missing switch geometry");
    return thumb.x + thumb.width / 2 > track.x + track.width / 2;
  });
  await expect.poll(thumbIsOnRight).toBe(false);
  await preference.evaluate(element => element.setAttribute("dir", "ltr"));
  await expect.poll(thumbIsOnRight).toBe(true);
});

