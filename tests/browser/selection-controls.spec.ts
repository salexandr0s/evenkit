test("copy reports rejected writes, retries the real clipboard and clears stale results when text changes", async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/#copy-action");
  const region = page.getByRole("region", { name: "Clipboard recovery example" });
  const copy = region.getByRole("button", { name: "Copy project reference", exact: true });
  await copy.press("Enter");
  await expect(region.getByRole("status")).toHaveText("Could not copy. Try again.");
  await expect(copy).toBeFocused();
  await region.getByRole("checkbox", { name: "Simulate clipboard failure" }).uncheck();
  await copy.press("Enter");
  await expect(region.getByRole("status")).toHaveText("Copied to clipboard.");
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("project:field-notes");
  await expect(copy).toBeFocused();
  await region.getByRole("button", { name: "Change reference" }).click();
  await expect(region.getByRole("status")).toHaveText("");
  await copy.press("Enter");
  await expect(region.getByRole("status")).toHaveText("Copied to clipboard.");
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("project:release-plan");
});

test("progress can become indeterminate while meter retains its measurement", async ({ page }) => {
  await page.goto("/#progress");
  const region = page.getByRole("region", { name: "Progress and meter example" });
  const progress = region.getByRole("progressbar", { name: "Sample file preparation", exact: true });
  const meter = region.getByRole("meter", { name: "Workspace storage", exact: true });
  await expect(progress).toHaveAttribute("value", "25");
  await region.getByRole("button", { name: "Advance preparation" }).click();
  await expect(progress).toHaveAttribute("value", "50");
  await region.getByRole("checkbox", { name: "Unknown total" }).check();
  await expect(progress).not.toHaveAttribute("value");
  await expect(region.getByRole("button", { name: "Advance preparation" })).toBeDisabled();
  await expect(meter).toHaveAttribute("value", "38");
  await expect(meter).toHaveAttribute("aria-valuetext", "38 GB of 100 GB");
  await region.getByRole("button", { name: "Reset preparation" }).click();
  await expect(progress).toHaveAttribute("value", "25");
});
