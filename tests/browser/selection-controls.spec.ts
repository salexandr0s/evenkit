import { expect, test } from "@playwright/test";

test("checkboxes submit native values, restore mixed state, and recover group validation", async ({ page }) => {
  await page.goto("/#checkbox");
  const region = page.getByRole("region", { name: "Checkbox form example" });
  const email = region.getByRole("checkbox", { name: "Email", exact: true });
  const inbox = region.getByRole("checkbox", { name: "Workspace inbox", exact: true });
  const mixed = region.getByRole("checkbox", { name: "Partial approval", exact: true });
  await expect(email).toBeChecked();
  await expect(mixed).toHaveAttribute("aria-checked", "mixed");
  await expect(region.getByRole("checkbox", { name: "SMS, managed by the organization" })).toBeDisabled();
  await region.getByRole("button", { name: "Inspect values" }).click();
  await expect(region.getByRole("status")).toHaveText("Channels: email. Approval: not confirmed.");
  await mixed.click();
  await inbox.check();
  await region.getByRole("button", { name: "Inspect values" }).click();
  await expect(region.getByRole("status")).toHaveText("Channels: email, inbox. Approval: confirmed.");
  await region.getByRole("button", { name: "Reset choices" }).click();
  await expect(email).toBeChecked();
  await expect(inbox).not.toBeChecked();
  await expect(mixed).toHaveAttribute("aria-checked", "mixed");
  await email.uncheck();
  await region.getByRole("button", { name: "Inspect values" }).click();
  await expect(region.getByRole("alert")).toHaveText("Choose at least one delivery channel.");
  await expect(email).toBeFocused();
  await email.check();
  await region.getByRole("button", { name: "Inspect values" }).click();
  await expect(region.getByRole("alert")).toHaveCount(0);

  await page.setViewportSize({ width: 360, height: 900 });
  const target = await email.boundingBox();
  expect(target?.width).toBeGreaterThanOrEqual(44);
  expect(target?.height).toBeGreaterThanOrEqual(44);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const rtl = region.locator('[dir="rtl"]');
  const rtlControl = await rtl.getByRole("checkbox").boundingBox();
  const rtlLabel = await rtl.locator("label").boundingBox();
  expect(rtlControl!.x).toBeGreaterThanOrEqual(rtlLabel!.x + rtlLabel!.width);
});

