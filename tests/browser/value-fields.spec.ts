import { expect, test } from "@playwright/test";

test("MultiSelect searches IDs, expands overflow, removes values and honors native validation and fieldsets", async ({ page }) => {
  await page.goto("/#multi-select");
  const input = page.getByRole("combobox", { name: "Project members", exact: true });
  const form = page.getByRole("form", { name: "Project members form" });
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("members"))).toEqual(["alex", "sam", "lee", "jules"]);
  await form.getByRole("button", { name: "+2 more", exact: true }).click();
  await form.getByRole("button", { name: "Remove Lee Chen", exact: true }).click();
  await expect(input).toBeFocused();
  await input.fill("Mika");
  await input.press("ArrowDown");
  await input.press("Enter");
  await input.press("Escape");
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("members"))).toEqual(["alex", "sam", "jules", "mika"]);
  await input.press("Backspace");
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("members"))).toEqual(["alex", "sam", "jules"]);
  await input.fill("Archived");
  await input.press("ArrowDown");
  await expect(page.getByRole("option", { name: "Archived account", exact: true })).toHaveAttribute("aria-disabled", "true");
  await input.press("Enter");
  await input.press("Escape");
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("members"))).toEqual(["alex", "sam", "jules"]);
  await form.getByRole("button", { name: "Clear project members", exact: true }).click();
  await form.getByRole("button", { name: "Capture members", exact: true }).click();
  expect(await form.evaluate(node => (node as HTMLFormElement).checkValidity())).toBe(false);
  await expect(input).toBeFocused();
  await form.getByRole("button", { name: "Reset members", exact: true }).click();
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("members"))).toEqual(["alex", "sam", "lee", "jules"]);
  const reviewers = page.getByRole("form", { name: "Reviewers form" });
  const reviewerInput = page.getByRole("combobox", { name: "Additional reviewers", exact: true });
  await reviewerInput.press("Backspace");
  await reviewers.evaluate(node => node.addEventListener("reset", event => event.preventDefault(), { once: true }));
  await reviewers.getByRole("button", { name: "Reset reviewers" }).click();
  expect(await reviewers.evaluate(node => new FormData(node as HTMLFormElement).getAll("reviewers"))).toEqual([]);
  await reviewers.getByRole("button", { name: "Reset reviewers" }).click();
  await expect(reviewers.getByRole("button", { name: "Remove Lee Chen" })).toBeVisible();
  await page.getByRole("button", { name: "Disable reviewer fieldset", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Additional reviewers", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Remove Lee Chen", exact: true }).last()).toBeDisabled();
});

test("TokenInput rejects duplicates, retains failed drafts, admits pasted values and resets", async ({ page }) => {
  await page.goto("/#token-input");
  const input = page.getByRole("textbox", { name: "Project labels", exact: true });
  const form = page.getByRole("form", { name: "Project labels form" });
  await input.fill("planning");
  await input.press("Enter");
  await expect(form.getByRole("alert")).toContainText("planning is already added.");
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("labels"))).toEqual(["Planning"]);
  await input.fill("A label much longer than the permitted length");
  await input.press("Enter");
  await expect(input).toHaveValue("A label much longer than the permitted length");
  expect(await form.evaluate(node => (node as HTMLFormElement).checkValidity())).toBe(false);
  await input.fill("");
  await input.evaluate(node => {
    const transfer = new DataTransfer(); transfer.setData("text/plain", "Review,Release,Operations");
    node.dispatchEvent(new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData: transfer }));
  });
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("labels"))).toEqual(["Planning", "Review", "Release", "Operations"]);
  await input.press("Backspace");
  await form.getByRole("button", { name: "Capture labels", exact: true }).click();
  await expect(form.getByRole("status").last()).toContainText("Labels: Planning, Review, Release.");
  await form.evaluate(node => node.addEventListener("reset", event => event.preventDefault(), { once: true }));
  await form.getByRole("button", { name: "Reset labels", exact: true }).click();
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).getAll("labels"))).toEqual(["Planning", "Review", "Release"]);
  await form.getByRole("button", { name: "Reset labels", exact: true }).click();
  await expect.poll(() => form.evaluate(node => new FormData(node as HTMLFormElement).getAll("labels"))).toEqual(["Planning"]);
  await page.getByRole("button", { name: "Disable label fieldset", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Internal labels", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Remove Internal", exact: true })).toBeDisabled();
});

test("NumberField preserves incomplete drafts, validates locale steps, submits canonical values and resets", async ({ page }) => {
  await page.goto("/#number-field");
  const input = page.getByRole("spinbutton", { name: "Quantity", exact: true });
  const form = page.getByRole("form", { name: "Quantity form" });
  await expect(input).toHaveValue("12,5");
  await input.fill("1,");
  await expect(input).toHaveValue("1,");
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).get("quantity"))).toBe("");
  await input.press("Tab");
  await expect(input).toHaveAttribute("aria-invalid", "true");
  expect(await form.evaluate(node => (node as HTMLFormElement).checkValidity())).toBe(false);
  await input.fill("0,25");
  await input.press("ArrowUp");
  await expect(input).toHaveValue("0,3");
  await input.fill("100");
  await expect(form.getByRole("button", { name: "Increase value" })).toBeDisabled();
  await input.fill("0,25");
  await form.getByRole("button", { name: "Increase value" }).click();
  await expect(input).toHaveValue("0,3");
  await form.getByRole("button", { name: "Capture quantity", exact: true }).click();
  await expect(form.getByRole("status").last()).toContainText("Quantity: 0.3.");
  await form.getByRole("button", { name: "Reset quantity", exact: true }).click();
  await expect(input).toHaveValue("12,5");
  await page.getByRole("combobox", { name: "Number locale", exact: true }).click();
  await page.getByRole("option", { name: "English · United States", exact: true }).click();
  await expect(input).toHaveValue("12.5");
  await input.fill("");
  await form.getByRole("button", { name: "Capture quantity", exact: true }).click();
  expect(await form.evaluate(node => (node as HTMLFormElement).checkValidity())).toBe(false);
  await expect(input).toBeFocused();
  await page.getByRole("button", { name: "Disable quantity fieldset", exact: true }).click();
  await expect(page.getByRole("spinbutton", { name: "Reserved quantity", exact: true })).toBeDisabled();
});

test("numeric recipes submit major currency units, percentage points and measurement values", async ({ page }) => {
  await page.goto("/#number-recipes");
  const form = page.getByRole("form", { name: "Budget form" });
  await form.getByRole("button", { name: "Capture budget", exact: true }).click();
  await expect(form.getByRole("status").last()).toContainText("Budget: 1250.5 EUR · Contingency: 12.5% · Weight: 2.75 kg.");
  const budget = page.getByRole("spinbutton", { name: "Project budget", exact: true });
  await budget.fill("2000");
  await form.evaluate(node => node.addEventListener("reset", event => event.preventDefault(), { once: true }));
  await form.getByRole("button", { name: "Reset budget", exact: true }).click();
  expect(await form.evaluate(node => new FormData(node as HTMLFormElement).get("budget"))).toBe("2000");
  await form.getByRole("button", { name: "Reset budget", exact: true }).click();
  await expect.poll(() => form.evaluate(node => new FormData(node as HTMLFormElement).get("budget"))).toBe("1250.5");
  await page.getByRole("spinbutton", { name: "Yen budget", exact: true }).fill("5000.5");
  await page.getByRole("spinbutton", { name: "Yen budget", exact: true }).press("Tab");
  await expect(page.getByRole("alert")).toContainText("Use up to 0 decimal places.");
});
