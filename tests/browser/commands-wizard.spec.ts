import { expect, test } from "@playwright/test";

test("command keyboard navigation preserves links, skips unavailable results, and hands focus to an action dialog", async ({ page }) => {
  await page.goto("/#command-palette");
  const open = page.getByRole("button", { name: "Open search", exact: true });
  await open.focus();
  await page.keyboard.press("Control+k");
  const dialog = page.getByRole("dialog", { name: "Search and commands" });
  const search = dialog.getByRole("searchbox", { name: "Search commands" });
  await expect(search).toBeFocused();
  const first = dialog.getByRole("link", { name: /Project directory/ });
  await expect(first).toHaveAttribute("href", "#data-table");
  await search.press("ArrowDown");
  await expect(first).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(dialog.getByRole("link", { name: /^Calendar/ })).toBeFocused();
  await page.keyboard.press("ArrowDown");
  const create = dialog.getByRole("button", { name: /^New project/ });
  await expect(create).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(dialog).not.toBeVisible();
  const project = page.getByRole("dialog", { name: "New project", exact: true });
  await expect(project.getByRole("textbox", { name: "Project name" })).toBeFocused();
  await project.getByRole("button", { name: "Close dialog" }).focus();
  await page.keyboard.press("Control+k");
  await expect(dialog).not.toBeVisible();
  await project.getByRole("button", { name: "Close dialog" }).click();
  await expect(project).not.toBeVisible();
  const notes = page.getByRole("textbox", { name: "Notes", exact: true });
  await notes.focus();
  await page.keyboard.press("Control+k");
  await expect(dialog).not.toBeVisible();
  await open.click();
  await search.press("Escape");
  await expect(open).toBeFocused();
});

test("remote command search retries, clears empty results, and discards an older query", async ({ page }) => {
  await page.goto("/#command-palette");
  await page.getByRole("checkbox", { name: "Fail the next search" }).check();
  await page.getByRole("button", { name: "Open search", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Search and commands" });
  await expect(dialog.getByText("Search could not be completed", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Try again", exact: true }).click();
  const search = dialog.getByRole("searchbox", { name: "Search commands" });
  await expect(dialog.getByRole("link", { name: /^Calendar/ })).toBeVisible();
  await search.fill("project");
  await expect(dialog.getByRole("status")).toHaveText("Searching…");
  // Let the debounced, deliberately slower request start before replacing it.
  await page.waitForTimeout(200);
  await search.fill("calendar");
  await expect(dialog.getByRole("link", { name: /^Calendar/ })).toBeVisible();
  await page.waitForTimeout(650);
  await expect(dialog.locator("[data-command-item]")).toHaveCount(1);
  await search.fill("no-such-command");
  await expect(dialog.getByText("No results. Try another search.", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Clear search", exact: true }).click();
  await expect(search).toHaveValue("");
  await expect(dialog.locator("[data-command-item]")).toHaveCount(5);
});

test("wizard validates, preserves answers through back navigation, and restores a saved draft", async ({ page }) => {
  await page.goto("/#onboarding-wizard");
  const wizard = page.getByRole("region", { name: "Workspace setup", exact: true });
  const next = wizard.getByRole("button", { name: "Continue", exact: true });
  await expect(next).toBeEnabled();
  await next.click();
  const summary = wizard.locator(".pk-form-summary");
  await expect(summary).toBeFocused();
  await summary.getByRole("link", { name: "Enter a workspace name." }).click();
  const workspace = wizard.getByRole("textbox", { name: "Workspace name" });
  await expect(workspace).toBeFocused();
  await workspace.pressSequentially("Meridian");
  await expect(workspace).toHaveValue("Meridian");
  await wizard.getByRole("textbox", { name: "Contact email" }).fill("alex@example.test");
  await next.click();
  await expect(wizard.getByRole("heading", { name: "Preferences", exact: true })).toBeFocused();
  await wizard.getByRole("checkbox", { name: "Send workspace updates" }).uncheck();
  await wizard.getByRole("button", { name: "Back", exact: true }).click();
  await expect(workspace).toHaveValue("Meridian");
  await next.click();
  await expect(wizard.getByRole("checkbox", { name: "Send workspace updates" })).not.toBeChecked();
  await wizard.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(wizard.getByRole("status")).toContainText("Draft saved.");
  await page.getByRole("button", { name: "Reopen setup", exact: true }).click();
  await wizard.getByRole("button", { name: "Resume draft", exact: true }).click();
  await expect(wizard.getByRole("heading", { name: "Preferences", exact: true })).toBeVisible();
  await next.click();
  await expect(wizard.getByRole("heading", { name: "Review your answers" })).toBeFocused();
  await expect(wizard.getByText("Meridian", { exact: true })).toBeVisible();
  await wizard.getByRole("button", { name: "Edit workspace", exact: true }).click();
  await expect(workspace).toHaveValue("Meridian");
});

test("wizard retries submission, cancels pending work, and separates successful setup from failed draft cleanup", async ({ page }) => {
  await page.goto("/#onboarding-wizard");
  const wizard = page.getByRole("region", { name: "Workspace setup", exact: true });
  await wizard.getByRole("textbox", { name: "Workspace name" }).fill("Aster");
  await wizard.getByRole("textbox", { name: "Contact email" }).fill("sam@example.test");
  await wizard.getByRole("button", { name: "Continue", exact: true }).click();
  await wizard.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("checkbox", { name: "Fail the next submission" }).check();
  await wizard.getByRole("button", { name: "Finish setup", exact: true }).click();
  await expect(wizard.getByRole("button", { name: "Cancel setup", exact: true })).toBeFocused();
  await expect(wizard.getByText("Setup was not completed", { exact: true })).toBeVisible();
  await wizard.getByRole("button", { name: "Retry setup", exact: true }).click();
  await wizard.getByRole("button", { name: "Cancel setup", exact: true }).click();
  await expect(wizard.getByRole("status")).toContainText("Operation cancelled.");
  await expect(wizard.getByRole("heading", { name: "Review your answers" })).toBeVisible();
  await page.getByRole("checkbox", { name: "Draft storage unavailable", exact: true }).check();
  await wizard.getByRole("button", { name: "Finish setup", exact: true }).click();
  await expect(wizard.getByRole("heading", { name: "Workspace is ready" })).toBeVisible();
  await expect(wizard.getByText("Saved draft remains", { exact: true })).toBeVisible();
  await expect(wizard.getByRole("button", { name: "Finish setup", exact: true })).toHaveCount(0);
  await page.getByRole("checkbox", { name: "Draft storage unavailable", exact: true }).uncheck();
  await wizard.getByRole("button", { name: "Retry draft cleanup" }).click();
  await expect(wizard.getByText("Saved draft remains", { exact: true })).toHaveCount(0);
});

test("wizard refuses incompatible draft versions and recovers from unavailable storage without discarding answers", async ({ page }) => {
  await page.goto("/#onboarding-wizard");
  await page.evaluate(() => localStorage.setItem("evenkit.catalog.onboarding.v1", JSON.stringify({ version: 99, stepId: "__review", savedAt: "2026-10-25T12:00:00Z", data: { workspace: "Old version", email: "old@example.test", updates: false, region: "eu" } })));
  await page.getByRole("button", { name: "Reopen setup", exact: true }).click();
  const wizard = page.getByRole("region", { name: "Workspace setup", exact: true });
  await expect(wizard.getByText(/This saved draft uses a different version/)).toBeVisible();
  const workspace = wizard.getByRole("textbox", { name: "Workspace name" });
  await expect(workspace).toHaveValue("");
  await workspace.fill("New workspace");
  await page.getByRole("checkbox", { name: "Draft storage unavailable", exact: true }).check();
  await wizard.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(wizard.getByText(/Your answers are still on this page/)).toBeVisible();
  await expect(workspace).toHaveValue("New workspace");
  await page.getByRole("checkbox", { name: "Draft storage unavailable", exact: true }).uncheck();
  await wizard.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(wizard.getByRole("status")).toContainText("Draft saved.");
});

test("cancelling draft cleanup after successful setup leaves a cleanup action without resubmitting", async ({ page }) => {
  await page.goto("/#onboarding-wizard");
  await page.getByRole("checkbox", { name: "Delay draft cleanup", exact: true }).check();
  const wizard = page.getByRole("region", { name: "Workspace setup", exact: true });
  await wizard.getByRole("textbox", { name: "Workspace name" }).fill("Cedar");
  await wizard.getByRole("textbox", { name: "Contact email" }).fill("cedar@example.test");
  await wizard.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(wizard.getByRole("status")).toContainText("Draft saved.");
  await wizard.getByRole("button", { name: "Continue", exact: true }).click();
  await wizard.getByRole("button", { name: "Continue", exact: true }).click();
  await wizard.getByRole("button", { name: "Finish setup", exact: true }).click();
  await wizard.getByRole("button", { name: "Cancel operation", exact: true }).click();
  await expect(wizard.getByRole("heading", { name: "Workspace is ready" })).toBeVisible();
  await expect(wizard.getByRole("button", { name: "Finish setup", exact: true })).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => localStorage.getItem("evenkit.catalog.onboarding.v1") !== null)).toBe(true);
  await wizard.getByRole("button", { name: "Retry draft cleanup" }).click();
  await expect.poll(() => page.evaluate(() => localStorage.getItem("evenkit.catalog.onboarding.v1"))).toBeNull();
});
