import { expect, test } from "@playwright/test";

test("website groups support keyboard navigation and preserve the selected destination", async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/#navbar");
  const website = page.locator(".navbar-website-example");
  const work = website.getByRole("button", { name: "Work", exact: true });
  await work.focus();
  await work.press("ArrowDown");
  await expect(page.getByRole("menuitem", { name: "Websites", exact: true })).toBeFocused();
  await page.keyboard.press("ArrowDown");
  const applications = page.getByRole("menuitem", { name: "Applications", exact: true });
  await expect(applications).toBeFocused();
  await applications.press("Enter");
  await expect(website.getByRole("heading", { name: "Tools for the way your team works.", exact: true })).toBeVisible();
  await expect(work).toBeFocused();
  await work.press("ArrowDown");
  await expect(applications).toHaveAttribute("aria-current", "page");
  await page.keyboard.press("Escape");
  await expect(applications).toBeHidden();
  await expect(work).toBeFocused();
  await website.getByRole("link", { name: /Northstar Studio/ }).click();
  await expect(website.getByRole("heading", { name: "We design websites and applications.", exact: true })).toBeVisible();
});

test("website contact and account actions update host state and restore focus", async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/#navbar");
  const website = page.locator(".navbar-website-example");
  const contact = website.getByRole("button", { name: "Contact", exact: true });
  await contact.click();
  const enquiry = page.getByRole("dialog", { name: "Contact Northstar", exact: true });
  await expect(enquiry.getByRole("textbox", { name: "Your name", exact: true })).toBeFocused();
  await enquiry.getByRole("textbox", { name: "Your name", exact: true }).fill("Taylor Lee");
  await enquiry.getByRole("textbox", { name: "Email address", exact: true }).fill("taylor@example.com");
  await enquiry.getByRole("textbox", { name: "About your project", exact: true }).fill("A website for our studio.");
  await enquiry.getByRole("button", { name: "Save enquiry", exact: true }).click();
  await expect(enquiry.getByRole("status")).toHaveText("Enquiry saved in this preview. Nothing was sent.");
  await page.keyboard.press("Escape");
  await expect(enquiry).toBeHidden();
  await expect(contact).toBeFocused();

  const signIn = website.getByRole("button", { name: "Sign in", exact: true });
  await signIn.focus();
  await expect(page.getByRole("tooltip", { name: "Sign in", exact: true })).toBeVisible();
  await signIn.press("Enter");
  const signInDialog = page.getByRole("dialog", { name: "Sign in to Northstar", exact: true });
  await signInDialog.getByRole("button", { name: "Use demo account", exact: true }).click();
  await expect(signInDialog).toBeHidden();
  const account = website.getByRole("button", { name: "Alex Morgan account", exact: true });
  await expect(account).toBeFocused();
  await account.press("ArrowDown");
  const profile = page.getByRole("menuitem", { name: "Your profile", exact: true });
  await expect(profile).toBeFocused();
  await profile.press("Enter");
  await expect(website.getByRole("heading", { name: "Alex Morgan", exact: true })).toBeVisible();
  await expect(account).toBeFocused();
  await account.click();
  await page.getByRole("menuitem", { name: "Sign out", exact: true }).click();
  await expect(signIn).toBeVisible();
  await expect(signIn).toBeFocused();
  await expect(website.getByRole("heading", { name: "We design websites and applications.", exact: true })).toBeVisible();
});

test("mobile website navigation keeps grouped links and contact reachable without losing dialog focus", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto("/#navbar");
  const website = page.locator(".navbar-website-example");
  const trigger = website.getByRole("button", { name: "Open studio navigation", exact: true });
  const signIn = website.getByRole("button", { name: "Sign in", exact: true });
  await expect(trigger).toBeVisible();
  await expect(signIn).toBeVisible();
  await expect(website.getByRole("button", { name: "Contact", exact: true })).toBeHidden();
  for (const control of [trigger, signIn]) {
    const bounds = await control.boundingBox();
    expect(bounds?.height).toBeGreaterThanOrEqual(44);
    expect(bounds?.width).toBeGreaterThanOrEqual(44);
  }
  await trigger.focus();
  await expect(page.getByRole("tooltip", { name: "Open studio navigation", exact: true })).toBeVisible();
  await trigger.press("Enter");
  const drawer = page.getByRole("dialog", { name: "Studio navigation", exact: true });
  await expect(drawer.getByRole("link", { name: "Studio", exact: true })).toBeFocused();
  await expect(drawer.getByRole("link", { name: "Websites", exact: true })).toBeVisible();
  await drawer.getByRole("link", { name: "Applications", exact: true }).click();
  await expect(drawer).toBeHidden();
  await expect(trigger).toBeFocused();
  await expect(website.getByRole("heading", { name: "Tools for the way your team works.", exact: true })).toBeVisible();
  await trigger.click();
  await expect(drawer.getByRole("link", { name: "Applications", exact: true })).toBeFocused();
  await page.setViewportSize({ width: 360, height: 420 });
  const lastDestination = drawer.getByRole("link", { name: "About", exact: true });
  const mobileContact = drawer.getByRole("button", { name: "Contact", exact: true });
  await lastDestination.focus();
  await expect(lastDestination).toBeInViewport();
  await expect(mobileContact).toBeInViewport();
  await lastDestination.press("Tab");
  await expect(mobileContact).toBeFocused();
  await mobileContact.click();
  const contactDialog = page.getByRole("dialog", { name: "Contact Northstar", exact: true });
  await expect(drawer).toBeHidden();
  await expect(contactDialog.getByRole("textbox", { name: "Your name", exact: true })).toBeFocused();
  await contactDialog.getByRole("textbox", { name: "Your name", exact: true }).fill("Taylor Lee");
  await page.keyboard.press("Escape");
  await expect(contactDialog).toBeHidden();
  await expect(trigger).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("resizing while a group or contact owns focus recovers to visible navigation", async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/#navbar");
  const website = page.locator(".navbar-website-example");
  const work = website.getByRole("button", { name: "Work", exact: true });
  await work.focus();
  await work.press("ArrowDown");
  const websites = page.getByRole("menuitem", { name: "Websites", exact: true });
  await expect(websites).toBeFocused();
  await page.setViewportSize({ width: 360, height: 800 });
  const trigger = website.getByRole("button", { name: "Open studio navigation", exact: true });
  await expect(websites).toBeHidden();
  await expect(trigger).toBeFocused();
  const menuTooltip = page.getByRole("tooltip", { name: "Open studio navigation", exact: true });
  await expect(menuTooltip).toBeVisible();
  await page.setViewportSize({ width: 1920, height: 1080 });
  await expect(trigger).toBeHidden();
  await expect(website.getByRole("navigation", { name: "Studio navigation", exact: true }).getByRole("link", { name: "Studio", exact: true })).toBeFocused();
  const contact = website.getByRole("button", { name: "Contact", exact: true });
  await contact.focus();
  await page.setViewportSize({ width: 768, height: 800 });
  await expect(trigger).toBeVisible();
  await expect(contact).toBeVisible();
  await expect(contact).toBeFocused();
  await expect(menuTooltip).toBeHidden();
  await contact.press("Enter");
  const enquiry = page.getByRole("dialog", { name: "Contact Northstar", exact: true });
  await expect(enquiry.getByRole("textbox", { name: "Your name", exact: true })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(contact).toBeFocused();
  // The navigation is already compact: hiding its separate action must still recover focus.
  await page.setViewportSize({ width: 640, height: 800 });
  await expect(contact).toBeHidden();
  await expect(trigger).toBeFocused();
});

test("application header and sidebar keep global and project destinations usable", async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/#navbar");
  const app = page.locator(".navbar-application-example");
  const account = app.getByRole("button", { name: "Workspace account", exact: true });
  // Focusing this lower example scrolls the page; its wrapper tooltip must survive it.
  await account.focus();
  await expect(account).toBeInViewport();
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
  await expect(page.getByRole("tooltip", { name: "Workspace account", exact: true })).toBeVisible();
  await expect(account).toHaveAttribute("aria-describedby", /.+/);
  await expect(page.getByRole("main")).toHaveCount(1);
  await app.getByRole("navigation", { name: "Workspace navigation", exact: true }).getByRole("link", { name: "Activity", exact: true }).click();
  await expect(app.getByRole("heading", { name: "Workspace activity", exact: true })).toBeVisible();
  await app.getByRole("navigation", { name: "Project navigation", exact: true }).getByRole("link", { name: "Team", exact: true }).click();
  await expect(app.getByRole("heading", { name: "Workspace team", exact: true })).toBeVisible();
  await app.getByRole("button", { name: "Support", exact: true }).click();
  await expect(app.getByRole("heading", { name: "Workspace support", exact: true })).toBeVisible();
  await app.getByRole("button", { name: "Workspace account", exact: true }).click();
  await page.getByRole("menuitem", { name: "Workspace profile", exact: true }).click();
  await expect(app.getByRole("heading", { name: "Your workspace account", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 360, height: 800 });
  await app.getByRole("button", { name: "Open navigation", exact: true }).click();
  const projectDrawer = page.getByRole("dialog", { name: "Project navigation", exact: true });
  await projectDrawer.getByRole("link", { name: "Projects", exact: true }).click();
  await expect(projectDrawer).toBeHidden();
  await expect(app.getByRole("heading", { name: "Workspace projects", exact: true })).toBeVisible();
  const workspaceTrigger = app.getByRole("button", { name: "Open workspace navigation", exact: true });
  await workspaceTrigger.click();
  const workspaceDrawer = page.getByRole("dialog", { name: "Workspace navigation", exact: true });
  await workspaceDrawer.getByRole("link", { name: "Activity", exact: true }).click();
  await expect(workspaceDrawer).toBeHidden();
  await expect(workspaceTrigger).toBeFocused();
  await expect(app.getByRole("heading", { name: "Workspace activity", exact: true })).toBeVisible();
});
